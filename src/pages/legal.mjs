function renderLegalPage(doc) {
  return {
    path: doc.path,
    title: doc.title,
    seoTitle: doc.seoTitle,
    schemaType: "WebPage",
    description: doc.description,
    breadcrumbLabel: doc.title,
    body: `
      <section class="doc-hero">
        <div class="shell doc-hero__grid">
          <p class="section-label section-label--light">Legal</p>
          <div>
            <h1>${doc.heading}</h1>
            <p class="doc-hero__updated">Last updated <time datetime="${lastUpdated.iso}">${lastUpdated.label}</time></p>
          </div>
        </div>
      </section>

      <section class="section legal-doc">
        <div class="shell legal-doc__grid">
          <p class="section-label">${doc.title}</p>
          <div class="legal-doc__body">
            ${doc.sections
              .map(
                ({ title, paragraphs, list }, index) => `
                  <h2><span>${String(index + 1).padStart(2, "0")}</span>${title}</h2>
                  ${paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("")}
                  ${list ? `<ul>${list.map((item) => `<li>${item}</li>`).join("")}</ul>` : ""}`,
              )
              .join("")}
            <p class="legal-doc__note">This document is provided for general information and does not constitute legal advice. For questions about Hartnett Capital, contact <a href="mailto:${site.email}">${site.email}</a> or visit the <a href="/contact/">contact page</a>.</p>
          </div>
        </div>
      </section>`,
  };
}

export const legalPages = legalDocuments.map(renderLegalPage);
