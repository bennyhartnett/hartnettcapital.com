function renderInsightArticle(article) {
  return {
    path: article.path,
    title: article.title,
    seoTitle: article.seoTitle,
    schemaType: "WebPage",
    description: article.description,
    breadcrumbs: [{ name: "Insights", path: "/insights/" }],
    breadcrumbLabel: article.title,
    ogType: "article",
    article: {
      headline: article.headline,
      datePublished: article.datePublished,
      dateModified: article.dateModified ?? article.datePublished,
    },
    body: `
      ${pageIntro({
        index: "06",
        eyebrow: "Insights",
        title: article.headline,
        copy: article.deck,
        variant: "blue",
      })}

      <section class="section article">
        <div class="shell article-grid">
          <p class="section-label">Perspective</p>
          <div>
            <div class="article-meta">
              <time datetime="${article.datePublished}">${article.dateLabel}</time>
              <span>${article.topic}</span>
              <span>${article.readingLabel}</span>
            </div>
            <div class="article-body reveal">
              ${article.sections
                .map(
                  ({ heading, paragraphs, list, afterList }) => `
                    <h2>${heading}</h2>
                    ${paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("")}
                    ${list ? `<ul>${list.map((item) => `<li>${item}</li>`).join("")}</ul>` : ""}
                    ${afterList ? afterList.map((paragraph) => `<p>${paragraph}</p>`).join("") : ""}`,
                )
                .join("")}
            </div>
            <div class="article-footer">
              ${linkArrow("All insights", "/insights/")}
              <span class="inline-link-separator" aria-hidden="true"></span>
              ${linkArrow("Share an opportunity", "/contact/")}
            </div>
          </div>
        </div>
      </section>

      <section class="section feature-quote">
        <div class="shell feature-quote__grid">
          <p class="section-label">In short</p>
          <div>
            <blockquote class="reveal">“${article.closing}”</blockquote>
            <p>If this perspective resonates with an asset you own, advise, or know well, we welcome a direct and confidential introduction.</p>
            ${linkArrow("Start a conversation", "/contact/")}
            <span class="inline-link-separator" aria-hidden="true"></span>
            ${linkArrow("Review our criteria", "/criteria/")}
          </div>
        </div>
      </section>`,
  };
}

export const insightArticlePages = insightArticles.map(renderInsightArticle);
